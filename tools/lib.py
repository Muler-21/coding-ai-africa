"""Builder helpers: write CSV data, run example code exactly as shown, capture output,
and emit content/stats-N.js for the app."""
import io, os, json, contextlib, textwrap
import numpy as np, pandas as pd

REPO = '/home/claude/repo-cafa'
DATA = os.path.join(REPO, 'content', 'data')
os.makedirs(DATA, exist_ok=True)

def save_csv(df, name):
    df.to_csv(os.path.join(DATA, name), index=False)
    return name

def run(code):
    """Run example code in the data folder and return what it prints."""
    code = textwrap.dedent(code).strip('\n')
    buf = io.StringIO(); cwd = os.getcwd(); os.chdir(DATA); ns = {'__name__': '__main__'}
    try:
        with contextlib.redirect_stdout(buf):
            exec(compile(code, '<example>', 'exec'), ns)
    finally:
        os.chdir(cwd)
    return code, buf.getvalue().rstrip(), ns

def example(id, t, q, design, csv, py, r, read, decide, biz=None):
    df = pd.read_csv(os.path.join(DATA, csv))
    code, out, ns = run(py)
    return {'_ns': ns, 'id': id, 't': t, 'q': q, 'design': design, 'csv': csv,
            'head': df.head(8).to_csv(index=False).strip(), 'n': int(len(df)),
            'py': code, 'r': textwrap.dedent(r).strip('\n'), 'out': out,
            'read': read, 'decide': decide, 'biz': biz}

def bi(en, am):
    """Bilingual label."""
    return {'en': en, 'am': am}

def rn(x, d=3):
    """Round numbers (and lists/arrays of numbers) for compact JSON."""
    if isinstance(x, (list, tuple, np.ndarray, pd.Series)):
        return [rn(v, d) for v in list(x)]
    return None if x is None or (isinstance(x, float) and np.isnan(x)) else round(float(x), d)

def emit(level, obj):
    for e in obj.get('ex', []):
        for k in [k for k in e if k.startswith('_')]:
            del e[k]
    path = os.path.join(REPO, 'content', f'stats-{level}.js')
    with open(path, 'w') as f:
        f.write(f'/* Statistics for Agriculture, level S{level}: generated by the build script; '
                'Python outputs were produced by running the code shown. */\n')
        f.write('window.STATS = window.STATS || {};\n')
        f.write(f'window.STATS[{level}] = ' + json.dumps(obj, ensure_ascii=False, indent=1) + ';\n')
    return path
